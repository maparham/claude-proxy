"""What the person typed in a Claude Code session, kept for the admin to read (the dashboard shows it to no one else).

Each request carries the whole conversation, so only its last user turn is looked at, and only the text the person
typed in it: no tool results, no files Claude read, no images, none of the blocks Claude Code adds itself, and never a
reply. A session with no title from Claude Code (titles.py) is named after its first prompt.
"""
from __future__ import annotations

import re
import sqlite3

MAX_PROMPT = 100_000   # characters kept of one prompt
MAX_TITLE = 80
AGENT_HEADER = "x-claude-code-agent-id"   # set on a subagent's requests: its prompt was written by Claude

# A block Claude Code wrote: one element from start to end (<system-reminder>, <local-command-stdout>, ...).
_WRAPPED = re.compile(r"<([a-z][a-z0-9-]*)>.*</\1>", re.S)
_COMMAND = re.compile(r"<command-name>\s*(.*?)\s*</command-name>", re.S)
_COMMAND_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
# A message typed while Claude was working arrives inside this wrapper, often beside tool results.
_MID_TURN = "The user sent a new message while you were working:"
_MID_TURN_END = "\n\nThis is how Claude Code surfaces"
# Turns Claude Code writes in the user's place (seen in 2.1.326): a subagent's report, compaction and its summary.
_HARNESS_STARTS = ("Another Claude session sent a message:", "CRITICAL: Respond with TEXT ONLY",
                   "This session is being continued from a previous conversation", "[Request interrupted by user",
                   "[handback-", "Caveat: The messages below were generated by the user while running local commands")


def wanted(session_id: str | None, method: str, path: str, headers, data: dict | None) -> bool:
    """True for a Claude Code session's own conversation requests. Its side requests (the session title, summaries)
    carry no tools, and a subagent's carry AGENT_HEADER."""
    return bool(session_id and method == "POST" and path == "/v1/messages" and isinstance(data, dict)
                and data.get("tools") and not headers.get(AGENT_HEADER))


def _texts(content) -> list[str]:
    if isinstance(content, str):
        return [content]
    if isinstance(content, list):
        return [b["text"] for b in content if isinstance(b, dict) and b.get("type") == "text" and isinstance(b.get("text"), str)]
    return []


def extract(data: dict) -> tuple[int, str] | None:
    """(the turn's place in the conversation, the typed text) of the request's last user turn; None when the person
    typed nothing in it (a tool result going back, a turn Claude Code wrote)."""
    messages = data.get("messages")
    if not isinstance(messages, list):
        return None
    seq = len(messages) - 1
    while seq >= 0 and isinstance(messages[seq], dict) and messages[seq].get("role") == "system":   # the environment note
        seq -= 1
    if seq < 0 or not isinstance(messages[seq], dict) or messages[seq].get("role") != "user":
        return None
    blocks = [t.strip() for t in _texts(messages[seq].get("content"))]
    local = any(b.startswith("<local-command-") for b in blocks)   # /compact, /model: run by Claude Code, not sent as a prompt
    typed, commands = [], []
    for b in blocks:
        if _MID_TURN in b:
            typed.append(b.split(_MID_TURN, 1)[1].split(_MID_TURN_END, 1)[0].replace("</system-reminder>", "").strip())
        elif m := _COMMAND.search(b):
            args = _COMMAND_ARGS.search(b)
            commands.append(f"{m.group(1)} {args.group(1).strip() if args else ''}".strip())
        elif b and not _WRAPPED.fullmatch(b) and not b.startswith(_HARNESS_STARTS):
            typed.append(b)
    if commands and not local:
        typed = commands   # a skill or custom command: the rest of the turn is the command's own text
    text = "\n\n".join(t for t in typed if t)[:MAX_PROMPT]
    return (seq, text) if text else None


def title_of(text: str) -> str:
    line = next((" ".join(l.split()) for l in text.splitlines() if l.strip()), "")
    return line if len(line) <= MAX_TITLE else line[:MAX_TITLE - 1].rstrip() + "…"


def save(conn: sqlite3.Connection, user_id: int, session_id: str, request_id: int | None, at: float, seq: int, text: str) -> bool:
    """Keeps the prompt once: a retry sends the same turn again. False when it was already there."""
    last = conn.execute("SELECT seq, text FROM prompts WHERE user_id=? AND session_id=? ORDER BY id DESC LIMIT 1",
                        (user_id, session_id)).fetchone()
    if last is not None and last["seq"] == seq and last["text"] == text:
        return False
    conn.execute("INSERT INTO prompts(user_id, session_id, request_id, at, seq, text) VALUES(?,?,?,?,?,?)",
                 (user_id, session_id, request_id, at, seq, text))
    # gclaude turns off Claude Code's non-essential traffic, its session-naming request with it, so the first prompt
    # names the session; a title from Claude Code replaces it (db.set_session_title).
    conn.execute("INSERT INTO session_titles(user_id, session_id, title, updated_at) VALUES(?,?,?,?) "
                 "ON CONFLICT(user_id, session_id) DO NOTHING", (user_id, session_id, title_of(text), at))
    return True


def of_session(conn: sqlite3.Connection, user_id: int, session_id: str) -> list[dict]:
    return [{"at": r["at"], "text": r["text"]} for r in conn.execute(
        "SELECT at, text FROM prompts WHERE user_id=? AND session_id=? ORDER BY id", (user_id, session_id))]
